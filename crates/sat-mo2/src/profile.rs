//! Profile files: `modlist.txt`, `plugins.txt`, `loadorder.txt`.
//!
//! `modlist.txt` is written highest priority first; [`Modlist`] keeps MO2 display order (lowest first).

use serde::{Deserialize, Serialize};

use sat_core::canon::{Entry, EntryKind, Modlist};

use crate::ini::strip_bom;

pub use sat_core::canon::SEPARATOR_SUFFIX;
const HEADER: &str = "# This file was automatically generated by Mod Organizer.";

/// Line ending and header of a parsed file, kept so that an unchanged list serializes byte-for-byte.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct TextStyle {
    pub crlf: bool,
    pub header: Option<String>,
    pub trailing_newline: bool,
    pub bom: bool,
}

impl Default for TextStyle {
    fn default() -> Self {
        Self {
            crlf: true,
            header: Some(HEADER.to_string()),
            trailing_newline: true,
            bom: false,
        }
    }
}

pub fn display_name(e: &Entry) -> &str {
    if e.kind == EntryKind::Separator {
        e.name.strip_suffix(SEPARATOR_SUFFIX).unwrap_or(&e.name)
    } else {
        &e.name
    }
}

/// Parses `modlist.txt` into display order.
pub fn parse_modlist(data: &[u8]) -> (Modlist, TextStyle) {
    let text = String::from_utf8_lossy(strip_bom(data));
    let style = TextStyle {
        crlf: text.contains("\r\n"),
        header: text
            .lines()
            .next()
            .filter(|l| l.starts_with('#'))
            .map(str::to_string),
        trailing_newline: text.ends_with('\n'),
        bom: data.starts_with(&[0xEF, 0xBB, 0xBF]),
    };
    let mut file_order = Vec::new();
    for line in text.lines() {
        let line = line.trim_end_matches('\r');
        let Some(first) = line.chars().next() else {
            continue;
        };
        let name = &line[first.len_utf8()..];
        let entry = match first {
            '+' | '-' if name.ends_with(SEPARATOR_SUFFIX) => Entry {
                name: name.to_string(),
                kind: EntryKind::Separator,
                enabled: false,
            },
            '+' => Entry {
                name: name.to_string(),
                kind: EntryKind::Mod,
                enabled: true,
            },
            '-' => Entry {
                name: name.to_string(),
                kind: EntryKind::Mod,
                enabled: false,
            },
            '*' => Entry {
                name: name.to_string(),
                kind: EntryKind::Foreign,
                enabled: true,
            },
            _ => continue,
        };
        file_order.push(entry);
    }
    file_order.reverse();
    (Modlist::new(file_order), style)
}

/// Serializes display order back into MO2's file order.
pub fn serialize_modlist(list: &Modlist, style: &TextStyle) -> Vec<u8> {
    let nl = if style.crlf { "\r\n" } else { "\n" };
    let mut lines: Vec<String> = Vec::with_capacity(list.entries.len() + 1);
    if let Some(h) = &style.header {
        lines.push(h.clone());
    }
    for e in list.entries.iter().rev() {
        let prefix = match e.kind {
            EntryKind::Foreign => '*',
            EntryKind::Separator => '-',
            EntryKind::Mod if e.enabled => '+',
            EntryKind::Mod => '-',
        };
        lines.push(format!("{prefix}{}", e.name));
    }
    let mut out = lines.join(nl);
    if style.trailing_newline {
        out.push_str(nl);
    }
    if style.bom {
        out.insert(0, '\u{feff}');
    }
    out.into_bytes()
}

/// One line of `plugins.txt` (`*Name.esp` = enabled).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct PluginLine {
    pub name: String,
    pub enabled: bool,
}

pub fn parse_plugins(data: &[u8]) -> Vec<PluginLine> {
    content_lines(data)
        .map(|l| match l.strip_prefix('*') {
            Some(n) => PluginLine {
                name: n.to_string(),
                enabled: true,
            },
            None => PluginLine {
                name: l.to_string(),
                enabled: false,
            },
        })
        .collect()
}

pub fn parse_loadorder(data: &[u8]) -> Vec<String> {
    content_lines(data).map(str::to_string).collect()
}

fn content_lines(data: &[u8]) -> impl Iterator<Item = &str> {
    std::str::from_utf8(strip_bom(data))
        .unwrap_or("")
        .lines()
        .map(str::trim)
        .filter(|l| !l.is_empty() && !l.starts_with('#'))
}

#[cfg(test)]
mod tests {
    use super::*;

    const SAMPLE: &str = "# This file was automatically generated by Mod Organizer.\r\n+Top Mod\r\n-Off Mod\r\n-UI_separator\r\n+Bottom Mod\r\n*DLC: Dawnguard\r\n";

    #[test]
    fn modlist_round_trip_is_byte_exact() {
        let (list, style) = parse_modlist(SAMPLE.as_bytes());
        let names: Vec<_> = list.entries.iter().map(|e| e.name.as_str()).collect();
        assert_eq!(
            names,
            [
                "DLC: Dawnguard",
                "Bottom Mod",
                "UI_separator",
                "Off Mod",
                "Top Mod"
            ]
        );
        assert_eq!(list.entries[2].kind, EntryKind::Separator);
        assert_eq!(display_name(&list.entries[2]), "UI");
        assert!(!list.entries[3].enabled);
        assert_eq!(serialize_modlist(&list, &style), SAMPLE.as_bytes());
    }

    #[test]
    fn lf_files_and_bom_survive() {
        let src = "\u{feff}+A\n-B\n";
        let (list, style) = parse_modlist(src.as_bytes());
        assert!(!style.crlf && style.header.is_none() && style.bom);
        assert_eq!(serialize_modlist(&list, &style), src.as_bytes());
    }

    #[test]
    fn plugins_and_loadorder() {
        let p = parse_plugins(b"# header\r\n*A.esp\r\nB.esp\r\n\r\n");
        assert_eq!(
            p,
            [
                PluginLine {
                    name: "A.esp".into(),
                    enabled: true
                },
                PluginLine {
                    name: "B.esp".into(),
                    enabled: false
                }
            ]
        );
        assert_eq!(parse_loadorder(b"Skyrim.esm\nA.esp\n"), ["Skyrim.esm", "A.esp"]);
    }
}
