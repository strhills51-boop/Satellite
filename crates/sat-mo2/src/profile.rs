//! Profile files: `modlist.txt`, `plugins.txt`, `loadorder.txt`. @sat:mo2.profile
//!
//! `modlist.txt` is written highest priority first; [`Modlist`] keeps MO2 display order (lowest first).
//!
//! Owns: byte-exact `modlist.txt`, `plugins.txt`, `loadorder.txt` parsing and writing.

use serde::{Deserialize, Serialize};

use sat_core::canon::{Entry, EntryKind, Modlist};

use crate::ini::strip_bom;

pub use sat_core::canon::SEPARATOR_SUFFIX;
const HEADER: &str = "# This file was automatically generated by Mod Organizer.";

/// Line ending and header of a parsed file, kept so that an unchanged list serializes byte-for-byte.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct TextStyle {
    pub crlf: bool,
    pub header: Option<String>,
    pub trailing_newline: bool,
    pub bom: bool,
}

impl Default for TextStyle {
    fn default() -> Self {
        Self {
            crlf: true,
            header: Some(HEADER.to_string()),
            trailing_newline: true,
            bom: false,
        }
    }
}

pub fn display_name(e: &Entry) -> &str {
    if e.kind == EntryKind::Separator {
        e.name.strip_suffix(SEPARATOR_SUFFIX).unwrap_or(&e.name)
    } else {
        &e.name
    }
}

/// Parses `modlist.txt` into display order.
pub fn parse_modlist(data: &[u8]) -> (Modlist, TextStyle) {
    let text = String::from_utf8_lossy(strip_bom(data));
    let style = TextStyle {
        crlf: text.contains("\r\n"),
        header: text
            .lines()
            .next()
            .filter(|l| l.starts_with('#'))
            .map(str::to_string),
        trailing_newline: text.ends_with('\n'),
        bom: data.starts_with(&[0xEF, 0xBB, 0xBF]),
    };
    let mut file_order = Vec::new();
    for line in text.lines() {
        let line = line.trim_end_matches('\r');
        let Some(first) = line.chars().next() else {
            continue;
        };
        let name = &line[first.len_utf8()..];
        let entry = match first {
            '+' | '-' if name.ends_with(SEPARATOR_SUFFIX) => Entry {
                name: name.to_string(),
                kind: EntryKind::Separator,
                enabled: false,
            },
            '+' => Entry {
                name: name.to_string(),
                kind: EntryKind::Mod,
                enabled: true,
            },
            '-' => Entry {
                name: name.to_string(),
                kind: EntryKind::Mod,
                enabled: false,
            },
            '*' => Entry {
                name: name.to_string(),
                kind: EntryKind::Foreign,
                enabled: true,
            },
            _ => continue,
        };
        file_order.push(entry);
    }
    file_order.reverse();
    (Modlist::new(file_order), style)
}

/// Serializes display order back into MO2's file order.
pub fn serialize_modlist(list: &Modlist, style: &TextStyle) -> Vec<u8> {
    let nl = if style.crlf { "\r\n" } else { "\n" };
    let mut lines: Vec<String> = Vec::with_capacity(list.entries.len() + 1);
    if let Some(h) = &style.header {
        lines.push(h.clone());
    }
    for e in list.entries.iter().rev() {
        let prefix = match e.kind {
            EntryKind::Foreign => '*',
            EntryKind::Separator => '-',
            EntryKind::Mod if e.enabled => '+',
            EntryKind::Mod => '-',
        };
        lines.push(format!("{prefix}{}", e.name));
    }
    let mut out = lines.join(nl);
    if style.trailing_newline {
        out.push_str(nl);
    }
    if style.bom {
        out.insert(0, '\u{feff}');
    }
    out.into_bytes()
}

/// One line of `plugins.txt`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct PluginLine {
    pub name: String,
    pub enabled: bool,
}

// @sat:mo2.plugins-txt
/// `plugins.txt` comes in two formats:
/// - **star format** (Skyrim SE / Fallout 4): `*Name.esp` = active, `Name.esp` = present but inactive;
/// - **list format** (older games): every listed plugin is active, there are no stars at all.
///
/// `stars` — the game's format (`GamePack::plugins.stars`): a star game's file is read as the star format even
/// without a single star — every plugin is off. Without `stars` a file with stars is still read as the star format.
/// Found on the owner's build (2026-11-19, MO2 2.5.2): 1 046 lines, zero stars, and MO2 shows every one of them
/// unchecked — only the base masters and Creation Club load. (2026-11-01 Satellite read that file as the list format
/// — all active — and was wrong.) Neither file is the whole truth: `loadorder.txt` gives the order.
pub fn parse_plugins(data: &[u8], stars: bool) -> Vec<PluginLine> {
    let lines: Vec<&str> = content_lines(data).collect();
    let star_format = stars || lines.iter().any(|l| l.starts_with('*'));
    lines
        .into_iter()
        .map(|l| match l.strip_prefix('*') {
            Some(n) => PluginLine {
                name: n.trim().to_string(),
                enabled: true,
            },
            None => PluginLine {
                name: l.to_string(),
                enabled: !star_format,
            },
        })
        .collect()
}

pub fn parse_loadorder(data: &[u8]) -> Vec<String> {
    content_lines(data).map(str::to_string).collect()
}

/// Comment lines at the top of a file and its line ending, kept when the file is rewritten.
fn head_of(previous: &[u8]) -> (Vec<String>, &'static str) {
    let text = std::str::from_utf8(strip_bom(previous)).unwrap_or("");
    let nl = if text.contains("\r\n") { "\r\n" } else { "\n" };
    let head = text
        .lines()
        .take_while(|l| l.trim_start().starts_with('#'))
        .map(str::to_string)
        .collect();
    (head, nl)
}

fn join(lines: Vec<String>, nl: &str) -> Vec<u8> {
    let mut out = lines.join(nl);
    out.push_str(nl);
    out.into_bytes()
}

// @sat:mo2.plugins-write
/// Writes `plugins.txt` in the game's format (`stars`, see [`parse_plugins`]) — for a game without it, in the format
/// of the file it replaces: star format marks active plugins with `*` and lists inactive ones bare; list format lists
/// active plugins only. Header comments and the line ending of the previous file are kept.
pub fn serialize_plugins(lines: &[(String, bool)], previous: &[u8], stars: bool) -> Vec<u8> {
    let star = stars
        || content_lines(previous).any(|l| l.starts_with('*'))
        || content_lines(previous).next().is_none();
    let (mut out, nl) = head_of(previous);
    for (name, active) in lines {
        match (star, active) {
            (true, true) => out.push(format!("*{name}")),
            (true, false) => out.push(name.clone()),
            (false, true) => out.push(name.clone()),
            (false, false) => {}
        }
    }
    join(out, nl)
}

/// Writes `loadorder.txt`, keeping the header comments and line ending of the file it replaces.
pub fn serialize_loadorder(names: &[String], previous: &[u8]) -> Vec<u8> {
    let (mut out, nl) = head_of(previous);
    out.extend(names.iter().cloned());
    join(out, nl)
}

fn content_lines(data: &[u8]) -> impl Iterator<Item = &str> {
    std::str::from_utf8(strip_bom(data))
        .unwrap_or("")
        .lines()
        .map(str::trim)
        .filter(|l| !l.is_empty() && !l.starts_with('#'))
}

#[cfg(test)]
mod tests {
    use super::*;

    const SAMPLE: &str = "# This file was automatically generated by Mod Organizer.\r\n+Top Mod\r\n-Off Mod\r\n-UI_separator\r\n+Bottom Mod\r\n*DLC: Dawnguard\r\n";

    #[test]
    fn modlist_round_trip_is_byte_exact() {
        let (list, style) = parse_modlist(SAMPLE.as_bytes());
        let names: Vec<_> = list.entries.iter().map(|e| e.name.as_str()).collect();
        assert_eq!(
            names,
            [
                "DLC: Dawnguard",
                "Bottom Mod",
                "UI_separator",
                "Off Mod",
                "Top Mod"
            ]
        );
        assert_eq!(list.entries[2].kind, EntryKind::Separator);
        assert_eq!(display_name(&list.entries[2]), "UI");
        assert!(!list.entries[3].enabled);
        assert_eq!(serialize_modlist(&list, &style), SAMPLE.as_bytes());
    }

    #[test]
    fn lf_files_and_bom_survive() {
        let src = "\u{feff}+A\n-B\n";
        let (list, style) = parse_modlist(src.as_bytes());
        assert!(!style.crlf && style.header.is_none() && style.bom);
        assert_eq!(serialize_modlist(&list, &style), src.as_bytes());
    }

    #[test]
    fn plugins_txt_without_stars_is_all_off_in_a_star_game() {
        let file = b"# This file was automatically generated by Mod Organizer.\r\nA.esm\r\nB.esl\r\n";
        // Skyrim SE: a line without a star is off — the owner's MO2 shows such a file all unchecked
        assert!(parse_plugins(file, true).iter().all(|l| !l.enabled));
        // an older game: the list format, every listed plugin active
        assert!(parse_plugins(file, false).iter().all(|l| l.enabled));
        let star = parse_plugins(b"*A.esm\r\nB.esl\r\n", false);
        assert_eq!((star[0].enabled, star[1].enabled), (true, false));
    }

    #[test]
    fn plugins_and_loadorder() {
        let p = parse_plugins(b"# header\r\n*A.esp\r\nB.esp\r\n\r\n", true);
        assert_eq!(
            p,
            [
                PluginLine {
                    name: "A.esp".into(),
                    enabled: true
                },
                PluginLine {
                    name: "B.esp".into(),
                    enabled: false
                }
            ]
        );
        assert_eq!(parse_loadorder(b"Skyrim.esm\nA.esp\n"), ["Skyrim.esm", "A.esp"]);
    }

    #[test]
    fn plugin_files_keep_their_format() {
        let lines = vec![("A.esp".to_string(), true), ("B.esp".to_string(), false)];
        let list = "# This file was automatically generated by Mod Organizer.\r\nA.esp\r\nOld.esp\r\n";
        // a star game writes stars whatever the file it replaces
        let out = serialize_plugins(&lines, list.as_bytes(), true);
        assert_eq!(
            out,
            b"# This file was automatically generated by Mod Organizer.\r\n*A.esp\r\nB.esp\r\n"
        );
        let parsed = parse_plugins(&out, true);
        assert!(parsed[0].enabled && !parsed[1].enabled);
        // an older game keeps the list format: active plugins only
        let out = serialize_plugins(&lines, list.as_bytes(), false);
        assert_eq!(
            out,
            b"# This file was automatically generated by Mod Organizer.\r\nA.esp\r\n"
        );
        assert!(parse_plugins(&out, false).iter().all(|l| l.enabled));
        // star format kept; a new file is star format
        assert_eq!(
            serialize_plugins(&lines, b"*A.esp\nB.esp\n", false),
            b"*A.esp\nB.esp\n"
        );
        assert_eq!(serialize_plugins(&lines, b"", false), b"*A.esp\nB.esp\n");
        assert_eq!(
            serialize_loadorder(&["X.esm".into()], b"# h\r\nY.esm\r\n"),
            b"# h\r\nX.esm\r\n"
        );
    }
}
