package mo2

import (
	"bytes"
	"testing"
)

func TestModlistRoundTrip(t *testing.T) {
	src := []byte("# This file was automatically generated by Mod Organizer.\r\n+Top Mod\r\n-Off Mod\r\n-UI_separator\r\n+Bottom Mod\r\n*DLC: Dawnguard\r\n")
	es := ParseModlist(src)
	if len(es) != 5 || es[0].Name != "DLC: Dawnguard" || !es[0].Unmanaged || es[4].Name != "Top Mod" {
		t.Fatalf("%+v", es)
	}
	if !es[2].Separator || es[2].DisplayName() != "UI" || es[3].Enabled {
		t.Fatalf("%+v", es)
	}
	if out := SerializeModlist(es); !bytes.Equal(out, src) {
		t.Fatalf("round trip:\n%q\n%q", out, src)
	}
}

func TestQColor(t *testing.T) {
	if c := DecodeQColor(`@Variant(\0\0\0\x43\x1\xff\xff\x80\x80\x30\x30\xd0\xd0\0\0)`); c != "#8030d0" {
		t.Fatal(c)
	}
	if c := DecodeQColor(`@Variant(\0\0\0\x43\0\x1\xff\xff\x10\x10\x20\x20\x30\x30\0\0)`); c != "#102030" {
		t.Fatal(c)
	}
}
